"""Optional interoperability audit, run in an ISOLATED reference environment.

Requires Amulet-Core 1.9.41 and its dependencies only in that test environment.
FacetEdit does not import them at runtime. Fixtures stay outside the project.
Usage: reference-python scripts/validate_construction_reference.py --fixtures PATH
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'src'))
from facetedit import nbt
from facetedit.blocks import AIR,Block
from facetedit.construction import load_construction,save_construction
from facetedit.model import Clipboard
from facetedit.registry import profile

import numpy as np
from amulet import Block as ReferenceBlock
from amulet.api.block_entity import BlockEntity
from amulet.api.selection import SelectionBox,SelectionGroup
from amulet.level.formats.construction import ConstructionFormatWrapper
from amulet.level.formats.construction.section import ConstructionSection
from amulet_nbt import StringTag,IntTag,ByteTag,CompoundTag,NamedTag


def describe(block):
    props=[];types=[]
    for k,v in block.properties.items():
        if isinstance(v,ByteTag):value='true' if v.py_int else 'false';kind=1
        elif isinstance(v,IntTag):value=str(v.py_int);kind=3
        else:value=v.py_str;kind=8
        props.append((k,value));types.append((k,kind))
    return Block(block.namespaced_name,tuple(props),tuple(types)),tuple(describe(b)[0] for b in block.extra_blocks)


def run(directory):
    directory.mkdir(parents=True,exist_ok=True)
    bedrock=profile('Bedrock 1.21.50')
    clips={
        'java_sparse':Clipboard((18,1,2),{(0,0,0):Block('stone'),(1,0,0):AIR,(17,0,1):Block.parse('oak_log[axis=z]')},offset=(-17,2,15)),
        'bedrock_layers':Clipboard((1,1,1),{(0,0,0):bedrock.initial('minecraft:oak_stairs')},'Bedrock',data_version=None,
                                  extra_blocks={(0,0,0):(bedrock.initial('minecraft:water'),)},game_version=(1,21,50)),
        'java_129_palette':Clipboard((129,1,1),{(x,0,0):Block('custom:block_'+str(x)) for x in range(129)}),
    }
    results=[]
    for name,clip in clips.items():
        file=directory/(name+'.construction');save_construction(clip,file)
        reference=ConstructionFormatWrapper(str(file))
        with file.open('rb') as handle:reference.open_from(handle)
        seen={};extras={}
        for sections in reference._chunk_to_section.values():
            for section in sections:
                for x,y,z in np.ndindex(section.shape):
                    pos=(section.sx+x,section.sy+y,section.sz+z)
                    native,layers=describe(section.palette[int(section.blocks[x,y,z])])
                    local=tuple(a-b for a,b in zip(pos,clip.offset))
                    seen[local]=native if clip.edition=='Bedrock' else Block(native.name,native.properties)
                    if layers:extras[local]=layers
        assert seen==clip.blocks,(name,seen,clip.blocks)
        assert extras==clip.extra_blocks,(name,extras,clip.extra_blocks)
        reference_file=directory/(name+'-reference-resaved.construction')
        with reference_file.open('wb') as handle:reference.save_to(handle)
        reopened=load_construction(reference_file)
        assert reopened.blocks==clip.blocks
        assert reopened.extra_blocks==clip.extra_blocks
        assert reopened.offset==clip.offset
        results.append({'fixture':name,'blocks':len(clip.blocks),'facetedit_to_amulet':'pass','amulet_resave_to_facetedit':'pass',
                        'sha256':hashlib.sha256(reference_file.read_bytes()).hexdigest()})
    # Independently construct a reference-owned section and block entity, rather
    # than round-tripping data initially generated by FacetEdit.
    file=directory/'reference-original.construction'
    reference=ConstructionFormatWrapper(str(file))
    reference.create_and_open('java',(1,21,4),SelectionGroup([SelectionBox((-16,5,0),(-14,6,2))]),overwrite=True)
    blocks=np.array([[[0,1]],[[1,0]]],dtype=np.uint32)
    palette=[ReferenceBlock('minecraft','chest'),ReferenceBlock('minecraft','oak_log',{'axis':StringTag('x')})]
    entity=BlockEntity('minecraft','chest',-16,5,0,NamedTag(CompoundTag({'id':StringTag('minecraft:chest'),'CustomName':StringTag('Independent 世界')})))
    reference._chunk_to_section={(-1,0):[ConstructionSection((-16,5,0),(2,1,2),blocks,palette,[],[entity])]}
    with file.open('wb') as handle:reference.save_to(handle)
    loaded=load_construction(file)
    assert loaded.blocks[(0,0,1)]==Block.parse('oak_log[axis=x]')
    assert nbt.get(nbt.loads(loaded.entities[(0,0,0)])[1],'CustomName')=='Independent 世界'
    assert loaded.offset==(-16,5,0)
    results.append({'fixture':'reference-original','reference_version':reference.version,'amulet_to_facetedit':'pass','block_entity':'pass','sha256':hashlib.sha256(file.read_bytes()).hexdigest()})
    return {'reference':'Amulet-Core 1.9.41','runtime_dependency_added':False,'cases':results}


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--fixtures',type=Path,required=True);args=parser.parse_args()
    print(json.dumps(run(args.fixtures),indent=2))
